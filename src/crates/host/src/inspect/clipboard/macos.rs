//! The general pasteboard through AppKit. `changeCount` and the types on the
//! pasteboard tell what a copy holds without reading it; reading the words,
//! the picture or the file links is what macOS may ask the person about, so
//! those reads wait until the bubble is pointed at.
use super::{ClipKind, FrontApp};
use objc2::AllocAnyThread;
use objc2_app_kit::{
    NSBitmapImageFileType, NSBitmapImageRep, NSPasteboard, NSPasteboardTypeFileURL,
    NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF, NSWorkspace,
};
use objc2_foundation::{NSDictionary, NSURL};

/// Types the nspasteboard.org convention uses for copies that must not be
/// shown or kept: passwords, one-time codes, copies an app made on its own.
const HIDDEN: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

pub(crate) fn change_count() -> Option<i64> {
    Some(NSPasteboard::generalPasteboard().changeCount() as i64)
}

pub(crate) fn peek() -> Option<ClipKind> {
    let board = NSPasteboard::generalPasteboard();
    let types: Vec<String> = board
        .types()
        .map(|types| types.iter().map(|kind| kind.to_string()).collect())
        .unwrap_or_default();
    kind_of(&types)
}

fn kind_of(types: &[String]) -> Option<ClipKind> {
    let has = |wanted: &str| types.iter().any(|kind| kind == wanted);
    if HIDDEN.iter().any(|hidden| has(hidden)) {
        return None;
    }
    // A Finder copy carries the files' icons as TIFF too, so files come first;
    // a page's copied picture carries a link besides, so the picture comes next.
    if has(&unsafe { NSPasteboardTypeFileURL }.to_string()) {
        return Some(ClipKind::Files);
    }
    if has(&unsafe { NSPasteboardTypePNG }.to_string())
        || has(&unsafe { NSPasteboardTypeTIFF }.to_string())
    {
        return Some(ClipKind::Image);
    }
    has(&unsafe { NSPasteboardTypeString }.to_string()).then_some(ClipKind::Text)
}

pub(crate) fn text() -> Option<String> {
    NSPasteboard::generalPasteboard()
        .stringForType(unsafe { NSPasteboardTypeString })
        .map(|text| text.to_string())
}

pub(crate) fn image_png() -> Option<Vec<u8>> {
    let board = NSPasteboard::generalPasteboard();
    if let Some(png) = board.dataForType(unsafe { NSPasteboardTypePNG }) {
        return Some(png.to_vec());
    }
    let tiff = board.dataForType(unsafe { NSPasteboardTypeTIFF })?;
    let bitmap = NSBitmapImageRep::initWithData(NSBitmapImageRep::alloc(), &tiff)?;
    let png = unsafe {
        bitmap.representationUsingType_properties(NSBitmapImageFileType::PNG, &NSDictionary::new())
    }?;
    Some(png.to_vec())
}

pub(crate) fn files() -> Vec<String> {
    let Some(items) = NSPasteboard::generalPasteboard().pasteboardItems() else {
        return Vec::new();
    };
    items
        .iter()
        .filter_map(|item| item.stringForType(unsafe { NSPasteboardTypeFileURL }))
        .filter_map(|link| NSURL::URLWithString(&link))
        .filter_map(|url| url.path())
        .map(|path| path.to_string())
        .collect()
}

pub(crate) fn front_app() -> Option<FrontApp> {
    let app = NSWorkspace::sharedWorkspace().frontmostApplication()?;
    Some(FrontApp {
        name: app.localizedName()?.to_string(),
        id: app.bundleIdentifier().map(|id| id.to_string()),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn types(list: &[&str]) -> Vec<String> {
        list.iter().map(|kind| kind.to_string()).collect()
    }

    #[test]
    fn a_hidden_copy_is_never_shown() {
        let copied = types(&["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]);
        assert_eq!(kind_of(&copied), None);
    }

    #[test]
    fn files_win_over_their_icons() {
        let copied = types(&["public.file-url", "public.tiff", "public.utf8-plain-text"]);
        assert_eq!(kind_of(&copied), Some(ClipKind::Files));
    }

    #[test]
    fn a_picture_wins_over_its_words() {
        let copied = types(&["public.png", "public.utf8-plain-text"]);
        assert_eq!(kind_of(&copied), Some(ClipKind::Image));
        assert_eq!(
            kind_of(&types(&["public.utf8-plain-text"])),
            Some(ClipKind::Text)
        );
        assert_eq!(kind_of(&types(&["com.apple.flat-rtfd"])), None);
    }
}
